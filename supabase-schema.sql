-- Run this SQL in Supabase Dashboard > SQL Editor.
create table if not exists public.inquiries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  full_name text not null,
  email text not null,
  phone text not null,
  company text,
  service text not null,
  budget text,
  message text not null
);

alter table public.inquiries enable row level security;

-- Public website visitors may submit inquiries, but cannot read or modify them.
create policy "Anyone can submit an inquiry"
on public.inquiries for insert
to anon, authenticated
with check (
  char_length(full_name) between 2 and 120 and
  char_length(email) between 5 and 254 and
  char_length(phone) between 8 and 18 and
  char_length(message) between 10 and 5000
);
